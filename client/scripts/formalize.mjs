const map = new Map(tone);
const keys = [...map.keys()].sort((a, b) => b.length - a.length);
const toneRe = new RegExp(
  `(?<![${L}])(?:${keys.map(esc).join("|")})(?![${L}])`,
  "g",
);
const brandRe = new RegExp(`(?<![${L}])${esc(OLD_BRAND)}(?![${L}])`, "g");

const hits = new Map(keys.map((k) => [k, 0]));
let brandHits = 0;
let changed = 0;

for (const file of files) {
  const before = fs.readFileSync(file, "utf8");
  const after = before
    .replace(toneRe, (m) => {
      hits.set(m, hits.get(m) + 1);
      return map.get(m);
    })
    .replace(brandRe, () => {
      brandHits++;
      return NEW_BRAND;
    });
  if (after !== before) {
    changed++;
    console.log(
      `${dry ? "[آزمایشی] " : ""}ویرایش: ${path.relative(".", file)}`,
    );
    if (!dry) fs.writeFileSync(file, after);
  }
}

const total = [...hits.values()].reduce((a, b) => a + b, 0);
console.log(
  `\n${changed} فایل، ${total} جمله‌ی لحن و ${brandHits} بار اسم «${NEW_BRAND}».`,
);

const missing = keys.filter((k) => hits.get(k) === 0);
if (missing.length) {
  console.log(
    `\nاین ${missing.length} جمله هیچ‌جا پیدا نشد (احتمالاً قبلاً تغییر کرده یا کمی فرق دارد):`,
  );
  for (const k of missing) console.log(`  - ${k}`);
}
